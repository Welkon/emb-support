#!/usr/bin/env python3
"""Extract SCMCU XC8 device registers into markdown facts.

The SCMCU IDE ships one device header per part under ``data/include``. The
headers carry no licence statement, so they are not copied into this
repository. This script reads them where they are installed and writes only
register names, addresses, and bit names.

Usage::

    sfr_extract.py --include-dir <SCMCU_IDE>/data/include \\
                   --out-dir skills/mcu-debug/references/sources/scmcu \\
                   --ide-version V2.00.16
    sfr_extract.py --check --include-dir ... --out-dir ...

``--check`` re-renders from the installed headers and fails when a committed
file differs, is missing, or is no longer produced. Run it after an IDE update.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import pathlib
import re
import sys

REGISTER = re.compile(
    r"^\s*volatile\s+unsigned\s+char\s+(\w+)\s*@\s*(0x[0-9A-Fa-f]+)\s*;", re.M
)
BIT = re.compile(
    r"^\s*volatile\s+bit\s+(\w+)\s*@\s*\(\(unsigned\)&(\w+)\*8\)\+(\d+)\s*;", re.M
)


class Problem(Exception):
    """A header that cannot be turned into a trustworthy map."""


def parse(path: pathlib.Path) -> tuple[list[tuple[str, int]], list[tuple[str, str, int]]]:
    text = path.read_text(errors="replace")
    registers: list[tuple[str, int]] = []
    address_of: dict[str, int] = {}
    for name, address in REGISTER.findall(text):
        value = int(address, 16)
        if name in address_of:
            if address_of[name] != value:
                raise Problem(f"{name} has addresses 0x{address_of[name]:X} and 0x{value:X}")
            continue
        address_of[name] = value
        registers.append((name, value))

    bits: list[tuple[str, str, int]] = []
    seen: set[str] = set()
    for name, register, index in BIT.findall(text):
        if name in seen:
            continue
        seen.add(name)
        bit = int(index)
        if bit > 7:
            raise Problem(f"bit {name} has index {bit}")
        if register not in address_of:
            raise Problem(f"bit {name} points at undeclared register {register}")
        bits.append((name, register, bit))

    if not registers:
        raise Problem("no registers parsed")
    registers.sort(key=lambda item: (item[1], item[0]))
    bits.sort(key=lambda item: (address_of[item[1]], item[2], item[0]))
    return registers, bits


def grouped(bits: list[tuple[str, str, int]]) -> dict[str, list[str]]:
    result: dict[str, list[str]] = {}
    for name, register, _ in bits:
        result.setdefault(register, []).append(name)
    return result


def render(part: str, path: pathlib.Path, digest: str, ide: str) -> str:
    registers, bits = parse(path)
    by_register = grouped(bits)
    banked = [address for _, address in registers if address > 0xFF]
    lines = [
        f"# SCMCU {part} Registers",
        "",
        "Generated by `skills/mcu-debug/scripts/scmcu/sfr_extract.py`; do not edit.",
        "Register names, addresses, and bit positions only. No vendor source is",
        "copied.",
        "",
        f"- Part: `{part}`",
        f"- Header: `data/include/{path.name}`",
        f"- SHA-256: `{digest}`",
        f"- IDE: `{ide}`",
        f"- Registers: {len(registers)}",
        f"- Bits: {len(bits)}",
    ]
    if banked:
        lines.append(
            f"- Addressing: banked, `0x{max(banked):X}` is the highest; the high "
            "byte is the bank, never truncate to the low byte"
        )
    else:
        lines.append("- Addressing: 8-bit, `0x00`-`0xFF`")
    lines += [
        "",
        "## Register map",
        "",
        "| Register | Address | Bits |",
        "| --- | --- | --- |",
    ]
    for name, address in registers:
        names = by_register.get(name, [])
        cell = ", ".join(f"`{bit}`" for bit in names) if names else "—"
        lines.append(f"| `{name}` | `0x{address:02X}` | {cell} |")

    known = {name for name, _ in registers}
    orphans = {
        register: names for register, names in by_register.items() if register not in known
    }
    if orphans:
        lines += ["", "## Bits on undeclared registers", ""]
        for register in sorted(orphans):
            names = ", ".join(f"`{name}`" for name in orphans[register])
            lines.append(f"- `{register}`: {names}")
    lines.append("")
    return "\n".join(lines)


def collect(include_dir: pathlib.Path) -> dict[str, pathlib.Path]:
    picked: dict[str, pathlib.Path] = {}
    for path in sorted(include_dir.glob("*.h")):
        if not path.stem.lower().startswith("sc8"):
            continue
        part = path.stem.upper()
        previous = picked.get(part)
        # The IDE ships some parts twice, differing only in file-name case.
        if previous is not None and previous.name.isupper():
            continue
        picked[part] = path
    return picked


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--include-dir", required=True, type=pathlib.Path)
    parser.add_argument("--out-dir", required=True, type=pathlib.Path)
    parser.add_argument("--ide-version", default=None)
    parser.add_argument("--only", nargs="*", help="part names, for a sample run")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()

    include_dir = args.include_dir
    if not include_dir.is_dir():
        print(f"include dir not found: {include_dir}", file=sys.stderr)
        return 2

    # `--check` has to reproduce the committed text, so it takes the IDE version
    # from the map it is checking unless the caller states one.
    ide_version = args.ide_version
    if ide_version is None and args.check and (args.out_dir / "index.json").exists():
        try:
            ide_version = json.loads((args.out_dir / "index.json").read_text()).get(
                "ide_version"
            )
        except ValueError:
            ide_version = None
    if ide_version is None:
        ide_version = "unknown"

    parts = collect(include_dir)
    if args.only:
        wanted = {part.upper() for part in args.only}
        parts = {part: path for part, path in parts.items() if part in wanted}
    if not parts:
        print("no SC8 headers found", file=sys.stderr)
        return 2

    rendered: dict[str, str] = {}
    index = {"ide_version": ide_version, "parts": []}
    for part in sorted(parts):
        path = parts[part]
        try:
            text = render(part, path, hashlib.sha256(path.read_bytes()).hexdigest(), ide_version)
        except Problem as problem:
            print(f"{part}: {problem}", file=sys.stderr)
            return 2
        rendered[f"{part}.md"] = text
        registers, bits = parse(path)
        index["parts"].append(
            {
                "id": part,
                "header": f"data/include/{path.name}",
                "sha256": hashlib.sha256(path.read_bytes()).hexdigest(),
                "registers": len(registers),
                "bits": len(bits),
            }
        )
    rendered["index.json"] = json.dumps(index, indent=2) + "\n"

    out_dir = args.out_dir
    if args.check:
        stale = []
        for name, text in sorted(rendered.items()):
            path = out_dir / name
            if not path.exists() or path.read_text() != text:
                stale.append(name)
        if not args.only:
            for path in sorted(out_dir.glob("SC8*.md")):
                if path.name not in rendered:
                    stale.append(f"{path.name} (no longer produced)")
        if stale:
            print("scmcu map is stale:", file=sys.stderr)
            for name in stale:
                print(f"  {name}", file=sys.stderr)
            return 1
        print(f"scmcu map: ok ({len(parts)} parts)")
        return 0

    out_dir.mkdir(parents=True, exist_ok=True)
    for name, text in sorted(rendered.items()):
        (out_dir / name).write_text(text)
    print(f"scmcu map: {len(parts)} parts, {out_dir}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
